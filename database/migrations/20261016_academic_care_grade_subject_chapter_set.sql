-- Additive-only taxonomy update; retain existing categories, folders, sets, questions, and submissions.
create table if not exists public.academic_care_chapters (
  id bigint generated by default as identity primary key,
  folder_id bigint not null references public.academic_care_folders(id) on update cascade on delete restrict,
  chapter_name text not null check (length(trim(chapter_name)) between 1 and 160),
  created_at timestamptz not null default now(),
  unique (folder_id, chapter_name)
);
alter table public.academic_care_sets add column if not exists chapter_id bigint;
alter table public.academic_care_questions add column if not exists chapter_id bigint;
alter table public.academic_care_question_bank_items add column if not exists chapter_id bigint;
do $$ begin
 if not exists(select 1 from pg_constraint where conname='academic_care_sets_chapter_id_fkey' and conrelid='public.academic_care_sets'::regclass) then
  alter table public.academic_care_sets add constraint academic_care_sets_chapter_id_fkey foreign key(chapter_id) references public.academic_care_chapters(id) on update cascade on delete restrict;
 end if;
 if not exists(select 1 from pg_constraint where conname='academic_care_questions_chapter_id_fkey' and conrelid='public.academic_care_questions'::regclass) then
  alter table public.academic_care_questions add constraint academic_care_questions_chapter_id_fkey foreign key(chapter_id) references public.academic_care_chapters(id) on update cascade on delete restrict;
 end if;
 if not exists(select 1 from pg_constraint where conname='academic_care_question_bank_items_chapter_id_fkey' and conrelid='public.academic_care_question_bank_items'::regclass) then
  alter table public.academic_care_question_bank_items add constraint academic_care_question_bank_items_chapter_id_fkey foreign key(chapter_id) references public.academic_care_chapters(id) on update cascade on delete restrict;
 end if;
end $$;
create index if not exists idx_academic_care_chapters_folder_id on public.academic_care_chapters(folder_id);
create index if not exists idx_academic_care_sets_chapter_id on public.academic_care_sets(chapter_id);
create index if not exists idx_academic_care_questions_chapter_id on public.academic_care_questions(chapter_id);
create index if not exists idx_academic_care_question_bank_items_chapter_id on public.academic_care_question_bank_items(chapter_id);
alter table public.academic_care_chapters enable row level security;
drop policy if exists academic_care_chapters_public_read on public.academic_care_chapters;
create policy academic_care_chapters_public_read on public.academic_care_chapters for select to public using (true);
drop policy if exists academic_care_chapters_admin_all on public.academic_care_chapters;
create policy academic_care_chapters_admin_all on public.academic_care_chapters for all to public using (academic_care_is_admin()) with check (academic_care_is_admin());